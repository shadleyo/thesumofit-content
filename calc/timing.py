def run(vid):
    words = json.load(open(f"calc/{vid}-words.json"))
    toks = [norm(w[0]) for w in words]
    def find(phrase, frm=0, end=False):
        p = [norm(x) for x in phrase.replace("-", "").split()]
        for i in range(frm, len(toks) - len(p) + 1):
            if toks[i:i + len(p)] == p:
                return i, (words[i + len(p) - 1][2] if end else words[i][1])
        raise SystemExit(f"{vid}: phrase not found: {phrase!r}")
    cur, starts = 0, []
    for phrase, _ in PLAN[vid]:
        i, t = find(phrase, cur); starts.append((i, t)); cur = i
    audio_end = words[-1][2]
    out = []
    for k, (phrase, cues) in enumerate(PLAN[vid]):
        si, st = starts[k]
        nxt = starts[k + 1][1] if k + 1 < len(starts) else audio_end + 2.8
        s0 = 0 if k == 0 else round(st * FPS)
        s1 = round(nxt * FPS)
        cf = []
        for c in cues:
            if isinstance(c, tuple) and c[0] == "+": f = c[1]
            elif isinstance(c, tuple): f = round(find(c[1], si, end=True)[1] * FPS) - s0 + (6 if c[0] == "after" else 0)
            else: f = round(find(c, si)[1] * FPS) - s0
            cf.append(max(0, f))
        out.append({"dur": s1 - s0, "cues": cf})
    json.dump(out, open(f"src/videos/{vid}.timing.json", "w"))
    print(vid, [(o["dur"], o["cues"]) for o in out], "total", sum(o["dur"] for o in out))

import sys
for v in (sys.argv[1:] or PLAN): run(v)
